"""DEMO 19: EY's nine Responsible AI principles applied to our RAG demo.

No API key or external package required. Prints a learning checklist and
runs simple automatic checks against this project where possible.
Official EY principle labels: Accountability, Data protection, Reliability,
Security, Transparency, Explainability, Fairness, Compliance, Sustainability.
This is NOT an EY assessment or certification of compliance.
"""
import csv
from pathlib import Path

# Not imported from rag_core, so the embedding model and ChromaDB are not loaded.
PROJECT_DIR = Path(__file__).resolve().parent
DOCUMENTS_DIR = PROJECT_DIR / "Documents"


def exists(name: str) -> bool:
    return (PROJECT_DIR / name).exists()


def file_contains(name: str, *phrases: str) -> bool:
    path = PROJECT_DIR / name
    if not path.exists():
        return False
    text = path.read_text(encoding="utf-8", errors="ignore").lower()
    return any(p.lower() in text for p in phrases)


# ==========================================
# AUTOMATIC PROJECT CHECKS
# ==========================================

documents = sorted(DOCUMENTS_DIR.glob("*.txt")) if DOCUMENTS_DIR.exists() else []
ignore_path = PROJECT_DIR / ".gitignore"
ignore_lines = ignore_path.read_text(encoding="utf-8").splitlines() if ignore_path.exists() else []
env_ignored = ".env" in [line.strip() for line in ignore_lines]
has_guardrails = exists("guardrails.py")
main_uses_guardrails = file_contains("main.py", "from guardrails import")
app_has_disclosure = file_contains("app.py", "ai-generated", "generated by ai", "may be inaccurate")

print("Documents found:", len(documents), [d.name for d in documents])
print(".gitignore exists:", ignore_path.exists())
print(".env ignored by git:", env_ignored)
print("Guardrails module (guardrails.py):", has_guardrails)
print("main.py uses guardrails:", main_uses_guardrails)
print("app.py shows an AI-generated disclosure:", app_has_disclosure)
print("\nThree governance domains: Purposeful design | Agile governance | Vigilant supervision")

# ==========================================
# CHECKLIST
# ==========================================

checks = [
    ("Accountability",
     "Who owns the RAG app and reviews failures? (10_log_ai_feedback.py logs answers and feedback)",
     "REQUIRES HUMAN OWNER"),
    ("Data protection",
     "Avoid sending employee identifiers to external models (guardrails.py blocks PII before OpenRouter)",
     "GUARDRAIL ACTIVE" if main_uses_guardrails else "MANUAL REVIEW"),
    ("Reliability",
     "Run evaluate.py / benchmark.py to compare question results; 15_hallucination_test.py for unsupported answers",
     "TEST AVAILABLE" if exists("evaluate.py") or exists("benchmark.py") else "NO TEST YET"),
    ("Security",
     "Keep API keys out of source control (.env must be listed in .gitignore)",
     "OK" if env_ignored else "ACTION NEEDED: add .env to .gitignore"),
    ("Transparency",
     "Tell users that generated answers are AI-generated",
     "OK" if app_has_disclosure else "ADD UI DISCLOSURE"),
    ("Explainability",
     "Show retrieved source chunk IDs and excerpts (16_source_trace.py)",
     "DEMO AVAILABLE" if exists("16_source_trace.py") else "NO DEMO YET"),
    ("Fairness",
     "Compare equivalent policy questions across groups (e.g. same question for different roles/locations)",
     "NO DEMO YET"),
    ("Compliance",
     "Confirm organizational, legal and data-retention rules (incl. feedback CSV logs)",
     "MANUAL REVIEW"),
    ("Sustainability",
     "Compare model/infrastructure resource needs (compare_models.py measures model speed)",
     "MANUAL REVIEW"),
]

for principle, check, status in checks:
    print(f"\n{principle:16} | {status}")
    print(" ", check)

output_path = PROJECT_DIR / "ey_responsible_ai_checklist.csv"
with output_path.open("w", newline="", encoding="utf-8") as file:
    writer = csv.writer(file)
    writer.writerow(["EY principle", "Classroom check", "Status"])
    writer.writerows(checks)

print("\nSaved:", output_path)
print("Reminder: this is a classroom learning checklist, not an EY assessment or certification.")
